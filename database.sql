CREATE DATABASE IF NOT EXISTS football_manager CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci;
USE football_manager;
CREATE TABLE IF NOT EXISTS users(
 id INT AUTO_INCREMENT PRIMARY KEY,
 name VARCHAR(100) NOT NULL,
 email VARCHAR(150) NOT NULL UNIQUE,
 password_hash VARCHAR(255) NOT NULL,
 created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP);
CREATE TABLE IF NOT EXISTS teams(
 id INT AUTO_INCREMENT PRIMARY KEY,
 name VARCHAR(100) NOT NULL UNIQUE,
 city VARCHAR(100) NOT NULL DEFAULT '',
 founded_year SMALLINT NULL,
 created_by INT NULL,
 FOREIGN KEY(created_by) REFERENCES users(id) ON DELETE SET NULL);
CREATE TABLE IF NOT EXISTS players(
 id INT AUTO_INCREMENT PRIMARY KEY,
 team_id INT NOT NULL,
 name VARCHAR(100) NOT NULL,
 position VARCHAR(30) NOT NULL,
 shirt_number TINYINT UNSIGNED NULL,
 FOREIGN KEY(team_id) REFERENCES teams(id) ON DELETE CASCADE);
CREATE TABLE IF NOT EXISTS matches(
 id INT AUTO_INCREMENT PRIMARY KEY,
 home_team_id INT NOT NULL,
 away_team_id INT NOT NULL,
 home_goals TINYINT UNSIGNED NOT NULL,
 away_goals TINYINT UNSIGNED NOT NULL,
 played_on DATE NOT NULL,
 FOREIGN KEY(home_team_id) REFERENCES teams(id) ON DELETE CASCADE,
 FOREIGN KEY(away_team_id) REFERENCES teams(id) ON DELETE CASCADE);
